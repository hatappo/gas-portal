import assert from 'node:assert/strict';
import { test } from 'node:test';
import { browser, bundleBrowser } from './helpers.mjs';

const client = await bundleBrowser({ connectSlack: true });
for (const service of ['github', 'slack']) test(`${service} masks stored tokens, explicitly replaces them, and never submits the mask`, t => {
  const app = browser(() => {}, client);
  t.after(() => app.dom.window.close());
  const get = id => app.document.getElementById(id);
  const connection = { id: '11111111-1111-4111-8111-111111111111', label: 'Demo@alex', login: 'alex', owner: '', tokenSuffix: 'aZ' };
  get('tab-settings').click(); get('settings-tab-sources').click();
  app.githubRequests[0].success({ ok: true, connections: service === 'github' ? [connection] : [] });
  app.slackRequests[0].success({ ok: true, connections: service === 'slack' ? [connection] : [] });
  const requests = service === 'github' ? app.githubRequests : app.slackRequests;
  const edit = () => get(service + '-connections').querySelector('button').click();
  const field = get(service + '-token');
  const replace = get('replace-' + service + '-token');
  const submit = () => get(service + '-settings-form').dispatchEvent(new app.dom.window.Event('submit', { cancelable: true }));
  edit();
  assert.equal(field.readOnly, true);
  assert.equal(field.type, 'text');
  assert.equal(field.value, '••••••••aZ');
  assert.equal(replace.hidden, false);
  submit();
  assert.equal(requests.at(-1).input.token, '');
  requests.at(-1).success({ ok: false, error: 'REQUEST_FAILED' });
  assert.equal(field.value, '••••••••aZ', 'Failed metadata-only save keeps the existing hint');
  replace.click();
  assert.equal(field.type, 'password');
  assert.equal(field.readOnly, false);
  assert.equal(field.value, '');
  assert.equal(app.document.activeElement, field);
  field.value = 'NEW_SECRET';
  submit();
  assert.equal(requests.at(-1).input.token, 'NEW_SECRET');
  assert.equal(field.value, '', 'Clear typed secrets immediately on submission');
  requests.at(-1).success({ ok: false, error: 'UNAUTHORIZED' });
  assert.equal(field.readOnly, false);
  assert.equal(field.value, '', 'Failed replacements are not restored to the DOM');
  submit();
  assert.equal(requests.at(-1).input.token, '', 'An empty replacement still preserves the saved token');
  requests.at(-1).success({ ok: true, connection: { ...connection, tokenSuffix: 'XY' } });
  edit();
  assert.equal(field.value, '••••••••XY');
  replace.click(); field.value = 'CANCELLED_SECRET';
  get('cancel-' + service).click();
  assert.equal(field.value, '');
  get('add-' + service).click();
  assert.equal(field.required, true);
  assert.equal(field.readOnly, false);
  assert.equal(field.type, 'password');
  assert.equal(field.value, '');
  assert.equal(replace.hidden, true);
});
