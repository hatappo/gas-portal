import { existsSync, lstatSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { githubUrl } from './repository-url.mjs';

export const PACKAGE_FILE = 'package.json';
/** Configuration lives under this key in the consumer's package.json, matching the package name. */
export const CONFIG_KEY = 'gas-portal';
export const GAS_FILES = ['appsscript.json', 'Code.js', 'Catalog.js', 'SheetCatalog.js', 'Index.html', 'Styles.html', 'Client.html'];
export const packageRoot = new URL('../', import.meta.url);
export const packageInfo = JSON.parse(readFileSync(new URL('package.json', packageRoot), 'utf8'));
export const validId = (value) => typeof value === 'string' && /^[A-Za-z0-9_-]+$/.test(value);

export function validateConfig(value, requireTarget = false) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error(`"${CONFIG_KEY}" in package.json must be a JSON object.`);
  const allowed = ['scriptId', 'deploymentId', 'authProfile', 'repositoryUrl'];
  for (const key of Object.keys(value)) if (!allowed.includes(key)) throw new Error(`Unknown configuration key: ${key}`);
  for (const key of ['scriptId', 'deploymentId']) {
    if (value[key] !== undefined && !validId(value[key])) throw new Error(`${key} must be an ID, not a URL.`);
  }
  if (value.authProfile !== undefined && (typeof value.authProfile !== 'string' || !/^[A-Za-z0-9][A-Za-z0-9_.-]{0,79}$/.test(value.authProfile))) {
    throw new Error('authProfile must start with a letter or digit and contain at most 80 letters, digits, hyphens, underscores, or dots.');
  }
  if (value.repositoryUrl !== undefined && (typeof value.repositoryUrl !== 'string' || (value.repositoryUrl !== '' && !githubUrl(value.repositoryUrl)))) {
    throw new Error('repositoryUrl must be a GitHub repository URL or an empty string.');
  }
  if (value.deploymentId && !value.scriptId) throw new Error('scriptId is required when deploymentId is set.');
  if (requireTarget && (!value.scriptId || !value.authProfile)) throw new Error(`Set scriptId and authProfile under "${CONFIG_KEY}" in package.json.`);
  return value;
}

export function readPackage(root) {
  const file = path.join(root, PACKAGE_FILE);
  if (!existsSync(file)) throw new Error('package.json is missing. Run portal init.');
  const text = readFileSync(file, 'utf8');
  const pkg = JSON.parse(text);
  if (!pkg || typeof pkg !== 'object' || Array.isArray(pkg)) throw new Error('Invalid package.json format.');
  return { file, text, pkg };
}

export function readConfig(root, requireTarget = false) {
  const { pkg } = readPackage(root);
  if (pkg[CONFIG_KEY] === undefined) throw new Error(`"${CONFIG_KEY}" is missing in package.json. Run portal init.`);
  return validateConfig(pkg[CONFIG_KEY], requireTarget);
}

export function assertRegular(file) {
  if (existsSync(file) && (!lstatSync(file).isFile() || lstatSync(file).isSymbolicLink())) throw new Error(`Refusing to modify a non-regular file: ${file}`);
}

/** Keep the indentation of a hand-edited package.json; default to two spaces. */
export function writePackage(file, pkg, text = '') {
  const indent = /^\{\r?\n([ \t]+)\S/.exec(text)?.[1] ?? 2;
  writeFileSync(file, JSON.stringify(pkg, null, indent) + '\n');
}

/** Rewrite only the configuration key; other fields keep their order and values. */
export function saveConfig(root, config) {
  validateConfig(config);
  assertRegular(path.join(root, PACKAGE_FILE));
  const { file, text, pkg } = readPackage(root);
  pkg[CONFIG_KEY] = config;
  writePackage(file, pkg, text);
}

/** Only modify owned output directories; protect unrelated files and symbolic links. */
export function generatedRoot(root) {
  const dir = path.join(root, '.portal');
  if (existsSync(dir)) {
    if (!lstatSync(dir).isDirectory() || lstatSync(dir).isSymbolicLink()) throw new Error('.portal must be a regular directory.');
    const marker = path.join(dir, 'generated.json');
    assertRegular(marker);
    if (!existsSync(marker) || JSON.parse(readFileSync(marker, 'utf8')).generator !== 'gas-portal') throw new Error('The existing .portal was not generated by gas-portal. Move it elsewhere before continuing.');
  } else {
    mkdirSync(dir);
    writeFileSync(path.join(dir, 'generated.json'), JSON.stringify({ generator: 'gas-portal' }) + '\n');
  }
  return dir;
}

export function prepareClasp(root, config) {
  const dir = generatedRoot(root);
  for (const name of ['.clasp.json', '.claspignore']) assertRegular(path.join(dir, name));
  writeFileSync(path.join(dir, '.clasp.json'), JSON.stringify({ scriptId: config.scriptId, rootDir: 'dist' }, null, 2) + '\n');
  writeFileSync(path.join(dir, '.claspignore'), '**/**\n' + GAS_FILES.map((file) => '!' + file).join('\n') + '\n');
  return dir;
}
